"""
Builds coverage.md (Part 11): every input from inputs.csv and every displayed-number group from the snapshot of the
dashboard (audit/after_cleanup.csv), each marked reviewed with finding IDs or "no issue (evidence: ...)".

    .venv/bin/python audit/logic_review/build_coverage.py
"""
import re
from collections import OrderedDict
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
inp = pd.read_csv(HERE / "inputs.csv").fillna("")
snap_cols = pd.read_csv(ROOT / "audit/after_cleanup.csv", nrows=1).columns[1:]

REPRO = "reproduced within 0.5% by the independent implementation (dashboard.md section 1)"
CHK = "audit/checks.py --quick passes (dashboard.md)"


def displayed_status(k):
    """Finding IDs / evidence for one displayed-number group (k uses <line>, <disease>, <year> placeholders)."""
    if k.startswith(("T.", "L.<line>.", "B.<disease>.")) or k in ("C.after_<year>", "C.deaths"):
        ids = []
        if "deaths" in k or "units" in k or "cov_drop" in k:
            ids += ["L-01", "L-43", "L-44"]
        if "infections" in k:
            ids += ["L-41"]
        if "_lo/_hi" in k:
            ids += ["L-02"]
        if "base" in k or "gross" in k:
            ids += ["L-06"]
        if "unit_cost" in k:
            ids += ["L-26", "L-16", "IMP-03"]
        if k in ("C.after_<year>", "C.deaths"):
            ids += ["L-33"]
        if "deaths_per_musd" in k:
            ids = ["L-01", "L-39"]
        return (", ".join(dict.fromkeys(ids)) + "; " if ids else "no issue (evidence: ") + REPRO + ("" if ids else ")")
    if k.startswith("C.part") or k.startswith("C.after_<year>_lo") or k.startswith("C.deaths_lo"):
        return "L-33, L-02; components checked against C.after_2030 (dashboard.md section 1)"
    if k.startswith("path."):
        return "no issue (evidence: dose-response curve uses the same draws at every point, model_section.py:101-104; checks.py year1_le_5year passes)"
    if k.startswith("Y."):
        return "L-29 (capacity flat over years); arithmetic: " + CHK + " (replacement never exceeds loss, health_model.py:680)"
    if k.startswith(("F.", "HB.")) or k == "break_even":
        return "L-29, L-31, L-34; fiscal inputs reviewed in inputs.csv (fiscal group)"
    if k.startswith("card."):
        return "L-01, L-39, L-18 (vaccine card constant 9,770 per US$1M); explained in dashboard.md section 4"
    if k.startswith("sum."):
        ids = "L-02 (range sums country percentiles), L-03 (71 countries)" if "lo/_hi" in k else "L-03 (71-country scope)"
        return ids + "; precomputed files rebuilt byte-identical (uncertainty_scope.md c); checks.py dashboard_country_equals_all_countries_row 28/28"
    if k == "n_countries":
        return "L-03; no issue in the count (evidence: 70 with aid of 71, model_data/dah_lines.csv)"
    return "reviewed"


groups = OrderedDict()
for c in snap_cols:
    k = re.sub(r"\.(hiv_\w+|tb_\w+|mal_\w+|imm)\.", ".<line>.", c)
    k = re.sub(r"\.(HIV|TB|Malaria|Immunization)\.", ".<disease>.", k)
    k = re.sub(r"_(lo|hi)$", "_lo/_hi", k)
    k = re.sub(r"20\d\d", "<year>", k)
    groups.setdefault(k, []).append(c)

out = ["# Part 11: Coverage table", "",
       "Every input from Part 1 and every displayed number from Part 5, each marked reviewed, with finding IDs or "
       "\"no issue (evidence: ...)\". No blanks. Generated by `build_coverage.py` from `inputs.csv` and the dashboard "
       "snapshot `audit/after_cleanup.csv` (every number the dashboard displays, 374 columns, grouped into 96 kinds).",
       "", "## A. Inputs (98)", "", "| Input ID | Group | Input | Reviewed | Findings or evidence |", "|---|---|---|---|---|"]
for _, r in inp.iterrows():
    f = r["finding"].strip()
    if not f or f == "no issue":
        ev = r["source_definition"] or r["source"]
        f = f"no issue (evidence: {r['concept_match'] or 'n/a'} match; {r['currency'] or 'n/a'}; {ev[:140]})"
    out.append(f"| {r['id']} | {r['group']} | {r['name_in_code'].replace('|', '/')} | yes | {f.replace('|', '/')} |")

out += ["", "## B. Displayed numbers (all pages), by kind", "",
        "`<line>` = each of the 11 money lines; `<disease>` = HIV, TB, Malaria, Immunization; `<year>` = 2026-2030 or "
        "2030. The Validation table inputs and All Countries rows are the `sum.` kinds.", "",
        "| Kind | Columns | Where shown | Reviewed | Findings or evidence |", "|---|---|---|---|---|"]
WHERE = {"T.": "Dashboard headline cards, story lede", "C.": "Further Deaths card and tooltip",
         "B.": "Section 4 disease charts, scenario comparison", "L.": "Service table, coverage chart",
         "path.": "Extra Deaths as More Aid Is Cut chart", "Y.": "Year-by-year chart, fiscal gap chart",
         "F.": "Can the Government Fill the Gap panel", "HB.": "Health budget panel", "card.": "US$1M cards",
         "break_even": "Health budget panel", "sum.": "All Countries pills, map, table; Validation",
         "n_countries": "All Countries pill"}
for k, cols in groups.items():
    where = next((v for p, v in WHERE.items() if k.startswith(p)), "Dashboard")
    out.append(f"| `{k}` | {len(cols)} | {where} | yes | {displayed_status(k)} |")

out += ["", "## C. Text, labels and charts without a number column", "",
        "| Item | Reviewed | Findings or evidence |", "|---|---|---|"]
TEXT = [
    ("Story headline and dek (claims C1-C3)", "L-48, L-01; dashboard.md section 5"),
    ("Range labels \"95% interval\" (C4, 10+ places)", "L-02"),
    ("Hero \"People Losing Care Each Year\" and breakdown (C5)", "L-40, L-01"),
    ("US$1M card footers \"aid lost per life lost\" (C6)", "no issue as arithmetic (evidence: US$5M / deaths, CARD_FOOT_TIP); L-01 for HIV"),
    ("All Countries pills and range tooltip (C7)", "L-03; range tooltip already discloses the overstatement (L-02)"),
    ("Validation comparison table and captions (C8, C16)", "L-47, L-11"),
    ("Methods cross-check summary \"lower bound ... most likely lies between\" (C9)", "L-48"),
    ("model_params.csv citation text (C10)", "L-01, L-26"),
    ("Preset descriptions (C11-C14)", "L-28, L-45, L-46, L-09, L-08, L-35"),
    ("Net Aid Lost sub-line (C15)", "no issue (evidence: labels kappa as an assumption, model_section.py:873-886)"),
    ("INTRO sentence (C17)", "L-48, L-01"),
    ("Infections tooltip, lives-first (C18)", "L-30"),
    ("Labels and time basis of every headline kind", "dashboard.md section 2; L-35 (MOU nominal), others no issue"),
    ("Section 1 chart: IHME health spending by source", "no issue (evidence: checks.py section1_2023_matches_raw_IHME_file 71/71; constant 2023 US$, Sept 2026 release)"),
    ("Section 1 vs Section 2 DAH", "no issue for the model (evidence: 6/630 country-years differ 2-4.4%, two IHME products; checks.py warnings)"),
    ("Section 2 charts: DAH by funder, channel, program area", "no issue (evidence: same IHME DAH file, elim_ch == 0, prepare_model.py:294)"),
    ("Section 3 treemap: revenue and spending", "L-31, L-38 (not rebuildable); I-10 logic checked by checks.py"),
    ("Per-person figures (population)", "L-31 (WEO vintage untagged)"),
    ("Country profile pills (Region, Income Group, MOU, GDP, Population)", "no issue (evidence: country_profile.csv rebuilt byte-identical; MOU status from KFF tracker 2026-10-08)"),
    ("Map and exposure scatter (All Countries)", "L-03; values = sum. kinds above"),
    ("Scenario comparison text \"Scenario B averts ...\"", "no issue (evidence: difference of two reproduced totals)"),
    ("MOU schedule chart and caption", "L-08, L-35"),
    ("Malaria Inputs table (Validation)", "L-07, L-21, L-22, L-23"),
    ("Donor money exceeds cost table (Validation)", "L-44"),
    ("Methods page formulas", "L-36, L-37 (spec completeness); formulas match code per independent reproduction"),
    ("Country brief (PDF export)", "same values as headline cards and US$1M cards (model_section.py _brief_html); same findings"),
]
out += [f"| {a} | yes | {b} |" for a, b in TEXT]
(HERE / "coverage.md").write_text("\n".join(out) + "\n")
print(len(inp), "inputs;", len(groups), "displayed kinds;", len(TEXT), "text items")
